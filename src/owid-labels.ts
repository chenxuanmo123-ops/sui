export function owidFieldLabel(key: string) { return OWID_FIELD_LABELS[key] }

/** True for the pinned OWID snapshot no matter how it arrived — built-in
 * download or a copy the reader saved and imported. The signature is the
 * upstream column set itself (100 of 130 keys must match), not the filename,
 * which a reader can change. Used only to choose display names. */
export function isOwidHeaders(headers: string[]) {
  let matched = 0
  for (const key of headers) if (OWID_FIELD_LABELS[key]) matched++
  return matched >= 100
}
