"""AI protocol UI test: API responses are explicit test doubles, never product data.
Calculations use the real OWID subset generated by browser_acceptance.py.
"""
import os, sys, csv, io, json, math
from pathlib import Path
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'.tools/python'))
(root/'artifacts').mkdir(exist_ok=True)
from playwright.sync_api import sync_playwright, expect
sys.stdout.reconfigure(encoding='utf-8')
url=os.environ.get('TEST_BASE_URL','http://127.0.0.1:5173')
subset=(root/'tests/fixtures/owid-China-2015-2022.csv').read_text(encoding='utf-8')
rows=list(csv.DictReader(io.StringIO(subset)))
assert len(rows)==8 and all(r['country']=='China' for r in rows)
checks=[]
def checked(message):
    checks.append(message); print('PASS '+message,flush=True)
mapping={'x':'year','metric':'renewables_electricity','filter':'country','value':'China','from':'2015','to':'2022','unit':'TWh','aggregate':'sum','timeBucket':'year','conditions':[]}
baseplan={'goal':'比较真实公开子集中的年度发电量','scene':'公开能源统计','grain':'每行一个地区一年','fieldRoles':[{'field':'year','meaning':'统计年','role':'time'}],'assumptions':[],'questions':[],'tasks':[{'id':'annual','title':'年度能源比较','rationale':'检视逐年分组结果','chart':'line','mapping':mapping}],'limitations':['描述统计不证明因果，样本不代表未上传地区']}
state={'plan_mode':'clarify_only','fail_review':True,'plan_requests':[],'review_requests':[]}
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,channel='msedge')
    context=browser.new_context(viewport={'width':1440,'height':1000},reduced_motion='reduce')
    page=context.new_page(); errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(url+'/',wait_until='networkidle')
    page.get_by_role('button',name='打开 AI 分析助手',exact=True).click()
    expect(page.locator('.ai-connection')).to_contain_text('连接你的 AI 模型')
    expect(page.get_by_role('button',name='理解数据并提出分析计划')).to_be_disabled()
    assert page.locator('#analysis-svg').count()==0
    checked('真实服务未配置时明确提示，不提供模拟 AI 结果')
    def intercept(route):
        path=route.request.url.split('/api/ai/')[1]
        if path=='status': return route.fulfill(json={'configured':True,'providers':[{'id':'contract','name':'仅测试替身','model':'test-contract'}]})
        body=route.request.post_data_json
        if path=='plan':
            state['plan_requests'].append(body)
            plan=json.loads(json.dumps(baseplan))
            if state['plan_mode']!='ready': plan['questions']=['请确认统计范围和单位']
            if state['plan_mode']=='clarify_only': plan['tasks']=[]
            return route.fulfill(json={'plan':plan,'datasetHash':body['dataset']['hash'],'providerName':'仅测试替身','model':'test-contract','generatedAt':'2026-10-15T00:00:00Z'})
        if path=='review':
            state['review_requests'].append(body)
            if state['fail_review']: return route.fulfill(status=502,json={'error':'测试故障：模型暂时不可用'})
            return route.fulfill(json={'review':{'answerability':'descriptive_only','findings':[{'statement':'所选年度分组存在差异，具体数值请查看引用。','evidenceIds':[body['facts'][0]['id']],'interpretation':'observation'}],'limitations':['仅基于所提供的端点和极值证据，不推断因果。'],'nextQuestions':['改看太阳能指标是否呈现相似变化？']}})
        route.abort()
    page.route('**/api/ai/*',intercept)
    page.reload(wait_until='networkidle')
    page.get_by_role('button',name='打开 AI 分析助手',exact=True).click()
    expect(page.locator('.ai-connection')).to_contain_text('仅测试替身')
    page.locator('#file-upload').set_input_files({'name':'owid-China-2015-2022.csv','mimeType':'text/csv','buffer':subset.encode('utf-8')})
    page.wait_for_function("document.querySelector('.dataset-name strong').textContent==='owid-China-2015-2022.csv' && !document.querySelector('.loading-indicator')")
    page.get_by_label('分析目标',exact=True).fill('比较中国逐年的可再生能源发电量，了解描述性变化。')
    expect(page.get_by_role('button',name='理解数据并提出分析计划')).to_be_enabled()
    assert page.locator('#business-context').input_value()==''
    page.get_by_role('button',name='理解数据并提出分析计划').click()
    expect(page.locator('.ai-questions')).to_contain_text('请确认统计范围和单位')
    assert page.get_by_role('button',name='确认计划并计算').count()==0
    assert page.locator('#analysis-svg').count()==0
    sent=state['plan_requests'][-1]
    assert 'rows' not in sent['dataset'] and all('examples' not in c for c in sent['dataset']['columns'])
    checked('仅输入问题即可规划，背景可空、默认不传单元格，无安全任务时等待澄清')
    state['plan_mode']='partial'
    # Keep background empty: questions must not block independently safe tasks.
    assert page.locator('#business-context').input_value()==''
    page.get_by_role('button',name='理解数据并提出分析计划').click()
    expect(page.locator('.ai-questions')).to_contain_text('这些问题不会阻止当前安全的描述性计算')
    expect(page.locator('.ai-tasks')).to_contain_text('年度能源比较')
    expect(page.get_by_role('button',name='确认计划并计算')).to_be_visible()
    expect(page.get_by_role('button',name='确认计划并计算')).to_be_disabled()
    assert page.locator('#analysis-svg').count()==0
    page.get_by_role('button',name='数据与来源',exact=True).click()
    page.get_by_role('button',name='分析工作台',exact=True).click()
    expect(page.locator('.ai-plan')).to_contain_text('年度能源比较')
    page.locator('.ai-plan input[type=checkbox]').check()
    expect(page.get_by_role('button',name='确认计划并计算')).to_be_enabled()
    page.get_by_role('button',name='确认计划并计算').click()
    expect(page.locator('.ai-error')).to_contain_text('已完成的真实计算仍可查看')
    expect(page.locator('#analysis-svg')).to_be_visible()
    resultrows=page.locator('.data-panel tbody tr')
    assert resultrows.count()==8
    for i,row in enumerate(rows):
        cells=resultrows.nth(i).locator('td').all_text_contents()
        assert cells[0]==row['year'] and math.isclose(float(cells[1].replace(',','')),float(row['renewables_electricity']),abs_tol=.0051)
    expect(page.locator('.ai-questions')).to_contain_text('请确认统计范围和单位')
    checked('问题与任务并存时允许确认并计算，8 个真实年度结果一致，解读失败保留计算和待确认提示')
    state['fail_review']=False
    page.get_by_role('button',name='重试 AI 解读（不重复计算）').click()
    expect(page.locator('.ai-review')).to_be_visible()
    page.locator('.ai-evidence').first.click()
    assert page.locator('.evidence-filter select').input_value()=='2015'
    assert rows[0]['renewables_electricity'] in page.locator('.source-list').inner_text()
    assert len(state['plan_requests'])==2 and len(state['review_requests'])==2
    page.get_by_role('button',name='分析分支',exact=False).click()
    assert page.locator('.branch-list > button').count()==1
    page.get_by_role('button',name='分析工作台',exact=True).click()
    checked('重试解读不重复计算，引用跳到正确原始记录，页面切换保留计划')
    # Real computation boundary checks; strings below are parser unit fixtures only.
    invariants=page.evaluate(r"""async()=>{
        const d=await import('/src/data.ts');
        const a=await import('/src/ai.ts');
        const invalid=['2026-02-30','2026-13-01','2026-01-01T29:00:00'].every(s=>{try{d.bucketLabel(s,'month');return false}catch{return true}});
        const ds={...d.parseCSV(['year,value','2015,2','2016,3'].join(String.fromCharCode(10))),fingerprint:'a'.repeat(64)};
        const m={x:'year',metric:'value',filter:'',value:'',from:'',to:'',unit:'',aggregate:'sum',timeBucket:'year',conditions:[{field:'year',operator:'gte',value:'2016'}]};
        const computed=await d.analyze(ds,m,'test',1);
        let stale=false;try{await a.executePlan(ds,{datasetHash:'b'.repeat(64),plan:{questions:[],tasks:[]}},'test',1)}catch{stale=true}
        return {invalid,month:d.bucketLabel('2026/3/2','month')==='2026-03',condition:computed.points.length===1&&computed.points[0].value===3&&computed.points[0].rowIds[0]===3,stale};
    }""")
    assert all(invariants.values()),invariants
    checked('有效日期分桶、无效日期拒绝、附加筛选来源和旧快照拒绝均通过')
    page.get_by_role('button',name='打开 AI 分析助手',exact=True).click()
    page.get_by_label('分析目标',exact=True).fill('改变分析方向')
    expect(page.locator('.ai-warning')).to_contain_text('旧计划')
    expect(page.get_by_role('button',name='确认计划并计算')).to_be_disabled()
    checked('改变目标使旧计划失效，不能继续执行旧口径')
    for width in [375,768,1440]:
        page.set_viewport_size({'width':width,'height':1000})
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    page.set_viewport_size({'width':1440,'height':1000})
    page.screenshot(path=str(root/'artifacts/ai-workbench-desktop.png'),full_page=True)
    assert not errors,errors
    (root/'artifacts/ai-validation.json').write_text(json.dumps({'checks':checks,'browser_errors':errors,'model_validation':'test doubles only; no live model call','data':'real OWID subset'},ensure_ascii=False,indent=2),encoding='utf-8')
    checked('AI 工作区响应式检查通过，无未捕获浏览器异常')
    browser.close()
