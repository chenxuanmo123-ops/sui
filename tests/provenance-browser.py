import sys, os, json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'.tools/python'))
from playwright.sync_api import sync_playwright, expect
sys.stdout.reconfigure(encoding='utf-8')
expect.set_options(timeout=30000)
out=root/'artifacts/provenance-acceptance';out.mkdir(parents=True,exist_ok=True)
checks=[]
def passed(text): checks.append(text);print('PASS '+text,flush=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,channel='msedge')
 page=browser.new_page(viewport={'width':1440,'height':1050},accept_downloads=True)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(os.environ.get('TEST_BASE_URL','http://127.0.0.1:5174'),wait_until='networkidle')
 page.locator('#file-upload').set_input_files(str(root/'tests/fixtures/uci-online-shoppers.csv'))
 page.get_by_role('button',name='数据与来源',exact=True).click()
 expect(page.locator('.source-details')).to_contain_text('UCI Machine Learning Repository')
 expect(page.locator('.source-details')).to_contain_text('原文件 SHA-256')
 expect(page.locator('.source-details')).to_contain_text('10.24432/C5F88Q')
 expect(page.locator('.source-details')).to_contain_text('CC BY 4.0')
 expect(page.locator('.source-details')).to_contain_text('不是营收金额')
 page.screenshot(path=str(out/'01-verified-public-source.png'),full_page=True)
 passed('原始公开CSV通过文件指纹匹配，页面显示机构、引用、许可和字段限制')
 page.locator('#file-upload').set_input_files(str(root/'tests/fixtures/owid-China-2015-2022.csv'))
 page.get_by_role('dialog',name='替换当前工作区？').get_by_role('button',name='替换并导入',exact=True).click()
 page.get_by_role('button',name='数据与来源',exact=True).click()
 expect(page.locator('.source-details')).to_contain_text('用户提供 · 未核验出处')
 page.locator('.source-editor > summary').click()
 page.get_by_label('出处：发布机构 / 平台',exact=True).fill('Our World in Data（上传者备注）')
 page.get_by_label('出处：来源页面',exact=True).fill('javascript:alert(1)')
 page.get_by_role('button',name='保存出处备注',exact=True).click()
 expect(page.locator('.source-editor [role=alert]')).to_contain_text('http / https')
 passed('自填脚本链接被拒绝，未知文件不会因名称而成为已核验来源')
 page.get_by_label('出处：来源页面',exact=True).fill('https://github.com/owid/energy-data')
 page.get_by_label('出处：推荐引用',exact=True).fill('来源为 OWID Energy Data；本文件为2015—2022年中国数据节选。')
 page.get_by_label('出处：数据范围与时效',exact=True).fill('中国，2015—2022；这是来源备注，待独立核验。')
 page.get_by_label('出处：来源备注',exact=True).fill('核对单位与上游来源；备注转义测试 <script>alert(1)</script>')
 page.get_by_role('button',name='保存出处备注',exact=True).click()
 expect(page.locator('.source-details')).to_contain_text('上传者备注 · 未独立核验')
 page.get_by_role('button',name='探索分析',exact=True).click()
 expect(page.locator('.dataset-source-note')).to_contain_text('上传者备注')
 page.get_by_label('探索分组字段').select_option('year')
 page.get_by_label('探索指标字段').select_option('renewables_electricity')
 page.get_by_role('button',name='执行探索分析',exact=True).click()
 expect(page.locator('.exploration-chart svg')).to_be_visible()
 with page.expect_download() as event:page.get_by_role('button',name='导出 HTML 证据报告',exact=True).click()
 target=out/'source-noted-exploration-report.html';event.value.save_as(str(target))
 html=target.read_text(encoding='utf-8')
 assert '数据出处与引用' in html and 'https://github.com/owid/energy-data' in html
 assert '上传者备注 · 未独立核验' in html and '当前数据快照 SHA-256' in html
 assert '&lt;script&gt;' in html and '<script>alert(1)</script>' not in html
 assert 'SELECT' in html and '<svg' in html
 passed('真实SQL探索后的HTML报告包含保存的出处、声明状态、指纹，备注经过转义')
 page.get_by_role('button',name='数据与来源',exact=True).click()
 expect(page.locator('.source-details')).to_contain_text('Our World in Data（上传者备注）')
 page.set_viewport_size({'width':390,'height':844})
 assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1')
 page.screenshot(path=str(out/'02-mobile-source-notes.png'),full_page=True)
 passed('来源备注在页面切换后保留，390px手机无整页横向溢出')
 page.get_by_role('button',name='数据处理',exact=True).click()
 page.get_by_label('处理字段',exact=True).select_option('year')
 page.get_by_label('置空标记',exact=True).fill('2015')
 page.get_by_label('删除所选字段为空的记录',exact=True).check()
 page.get_by_role('button',name='预览处理',exact=False).click()
 page.get_by_label('我已核对',exact=False).check()
 page.get_by_role('button',name='应用处理',exact=True).click()
 page.get_by_role('button',name='数据与来源',exact=True).click()
 expect(page.locator('.source-details')).to_contain_text('处理前快照 SHA-256')
 expect(page.locator('.source-details')).to_contain_text('上传者备注')
 passed('清理后的数据仍保留原文件指纹和已填写的出处')
 assert not errors,errors
 (out/'browser-checks.json').write_text(json.dumps({'checks':checks,'browserErrors':errors},ensure_ascii=False,indent=2),encoding='utf-8')
 browser.close()
print('PROVENANCE ACCEPTANCE PASSED',flush=True)
